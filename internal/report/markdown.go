package report

import (
	"fmt"
	"io"
	"strings"
)

// WriteMarkdown renders the report as Markdown, which is what a CI job posts
// as a pull-request comment or writes into a job summary.
//
// Every finding is an H3 with the severity in the heading, followed by the
// evidence and the fix, so a reviewer can read the whole report without
// terminal colours. The output is deliberately short: one table row per
// finding for scanning, and detail only for what was found.
func WriteMarkdown(w io.Writer, rep Report, opts TextOptions) error {
	var b strings.Builder

	fmt.Fprintf(&b, "## %s security report\n\n", rep.Tool)
	fmt.Fprintf(&b, "**Target:** `%s`  \n", rep.Target)
	fmt.Fprintf(&b, "**Scanned:** %s (%s, %d request(s))  \n",
		rep.StartedAt.Format("2006-01-02 15:04:05 MST"), formatDuration(rep.DurationMS), rep.Requests)
	fmt.Fprintf(&b, "**Result:** %s · risk %d/100 · %d issue(s)",
		gradeBadge(rep.Grade), rep.RiskScore, rep.Summary.Total)
	if rep.Suppressed > 0 {
		fmt.Fprintf(&b, " · %d known issue(s) suppressed by the baseline", rep.Suppressed)
	}
	b.WriteString("\n\n")

	s := rep.Summary
	fmt.Fprintf(&b, "| critical | high | medium | low | info |\n")
	fmt.Fprintf(&b, "| ---: | ---: | ---: | ---: | ---: |\n")
	fmt.Fprintf(&b, "| %d | %d | %d | %d | %d |\n\n", s.Critical, s.High, s.Medium, s.Low, s.Info)

	findings := rep.Findings()
	visible := findings[:0]
	for _, f := range findings {
		if f.Severity.AtLeast(opts.Min) {
			visible = append(visible, f)
		}
	}
	hidden := len(findings) - len(visible)

	if len(visible) == 0 {
		b.WriteString("No issues at or above the reporting threshold were found.\n")
		if hidden > 0 {
			fmt.Fprintf(&b, "\n_%d finding(s) below the severity filter are not shown._\n", hidden)
		}
		return writeAll(w, b.String())
	}

	b.WriteString("| severity | check | finding | url |\n")
	b.WriteString("| --- | --- | --- | --- |\n")
	for _, f := range visible {
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s |\n",
			f.Severity.Label(), f.CheckID, escapePipes(f.Title), inlineCode(f.URL))
	}
	b.WriteString("\n")

	for i, f := range visible {
		fmt.Fprintf(&b, "### %d. %s — %s\n\n", i+1, f.Severity.Label(), f.Title)
		if f.URL != "" {
			fmt.Fprintf(&b, "- **URL:** `%s`\n", f.URL)
		}
		if f.Evidence != "" {
			fmt.Fprintf(&b, "- **Evidence:** %s\n", escapePipes(f.Evidence))
		}
		if f.Remediation != "" {
			fmt.Fprintf(&b, "- **Fix:** %s\n", escapePipes(f.Remediation))
		}
		b.WriteString("\n")
	}

	if failed := failedChecks(rep); len(failed) > 0 {
		b.WriteString("### Checks that failed to run\n\n")
		for _, c := range failed {
			fmt.Fprintf(&b, "- `%s`: %s\n", c.ID, c.Error)
		}
		b.WriteString("\n")
	}

	if hidden > 0 {
		fmt.Fprintf(&b, "_%d finding(s) below the severity filter are not shown._\n\n", hidden)
	}

	fmt.Fprintf(&b, "---\n\n%s\n", "Generated by ["+rep.Tool+"](https://github.com/worztm/ijiya). Findings are heuristic leads: confirm each one before acting on it.")
	return writeAll(w, b.String())
}

// gradeBadge renders the letter grade without pretending an emoji is a colour.
func gradeBadge(grade string) string {
	if grade == "" {
		return "ungraded"
	}
	return "grade **" + grade + "**"
}

// escapePipes keeps table cells from splitting on a literal pipe in evidence.
func escapePipes(s string) string {
	return strings.ReplaceAll(strings.TrimSpace(s), "|", "\\|")
}

// inlineCode wraps a URL in backticks, or renders an em dash when absent.
func inlineCode(s string) string {
	if strings.TrimSpace(s) == "" {
		return "—"
	}
	return "`" + s + "`"
}

// writeAll flushes the assembled document.
func writeAll(w io.Writer, s string) error {
	_, err := io.WriteString(w, s)
	return err
}
